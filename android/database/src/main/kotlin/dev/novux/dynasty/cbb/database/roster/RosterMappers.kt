fun RosterPlayerSeed.toEntity(): DynastyRosterPlayerEntity =
    DynastyRosterPlayerEntity(
        playerId = playerId,
        dynastyId = dynastyId,
        positionWire = position.wire,
        classYearWire = classYear.wire,
        isStarter = isStarter,
        depthOrder = depthOrder,
        inTransferPortal = false,
        displayName = displayName,
        hometownCity = hometownCity,
        hometownState = hometownState,
        heightInches = heightInches,
        weightLbs = weightLbs,
        ovr = ovr,
        offRating = off,
        defRating = def,
        eligibilityYearsUsed = eligibility.yearsUsed,
        eligibilityYearsRemaining = eligibility.yearsRemaining,
        archetypeWire = archetypeWire,
        loyaltyRating = loyaltyRating,
        loyaltyPersonalityWire = loyaltyPersonalityWire,
        promiseTypeWire = promiseTypeWire,
        promiseStatusWire = promiseStatusWire,
        promiseLockedSeasonIndex = promiseLockedSeasonIndex,
        promiseStayTopN = promiseStayTopN,
        stamina = stamina,
        skinToneId = skinToneId,
        hairColorId = hairColorId,
        hairStyleId = hairStyleId,
        avatarPresetId = avatarPresetId,
    )

fun List<RosterPlayerSeed>.toEntities(): List<DynastyRosterPlayerEntity> = map { it.toEntity() }

fun DynastyRosterPlayerEntity.toDomain(): RosterPlayer {
    val position = PlayerPosition.fromWire(positionWire)
        ?: error("unknown position $positionWire")
    val classYear = PlayerClassYear.fromWire(classYearWire)
        ?: error("unknown class year $classYearWire")
    return RosterPlayer(
        playerId = playerId,
        dynastyId = dynastyId,
        position = position,
        classYear = classYear,
        isStarter = isStarter,
        depthOrder = depthOrder,
        inTransferPortal = inTransferPortal,
        declaredForDraft = declaredForDraft,
        draftStockPoints = draftStockPoints,
        proDayCompleted = proDayCompleted,
        displayName = displayName,
        hometownCity = hometownCity,
        hometownState = hometownState,
        heightInches = heightInches,
        weightLbs = weightLbs,
        nilUsdPerYear = nilUsdPerYear,
        nilDealRaisedThisSeason = nilDealRaisedThisSeason,
        ovr = ovr,
        off = offRating,
        def = defRating,
        eligibilityYearsUsed = eligibilityYearsUsed,
        eligibilityYearsRemaining = eligibilityYearsRemaining,
        medicalRedshirtSeason = medicalRedshirtSeason,
        injuryActive = injuryActive,
        injuryId = injuryId,
        injuryWeeksRemaining = injuryWeeksRemaining,
        injuryLabel = injuryLabel,
        injurySeverityWire = injurySeverityWire,
        injuryOccurredAtRsWeek = injuryOccurredAtRsWeek,
        injuryOccurredAtRsGameIndex = injuryOccurredAtRsGameIndex,
        rsGamesPlayedAtInjury = rsGamesPlayedAtInjury,
        rsGamesPlayedSeason = rsGamesPlayedSeason,
        injuryWasStarterSlotWire = injuryWasStarterSlotWire,
        injuryPriorRotationBand = injuryPriorRotationBand,
        starterSlotWire = starterSlotWire,
        gamesSuspendedRemaining = gamesSuspendedRemaining,
        academicHold = academicHold,
        gpaCurrent = gpaCurrent,
        academicCoverUp = academicCoverUp,
        conductIncidentId = conductIncidentId,
        archetypeWire = archetypeWire,
        loyaltyRating = loyaltyRating,
        loyaltyPersonalityWire = loyaltyPersonalityWire,
        promiseTypeWire = promiseTypeWire,
        promiseStatusWire = promiseStatusWire,
        promiseLockedSeasonIndex = promiseLockedSeasonIndex,
        promiseStayTopN = promiseStayTopN,
        promiseHistoryWire = promiseHistoryWire,
        stamina = stamina,
        skinToneId = skinToneId,
        hairColorId = hairColorId,
        hairStyleId = hairStyleId,
        avatarPresetId = avatarPresetId,
    )
}

